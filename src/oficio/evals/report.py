"""Turns a raw eval result into the table this project publishes.

The README's numbers come from here — never typed by hand. If a run has not
happened, the table says so rather than showing a stale figure.

Usage:
    python -m oficio.evals.run all --json evals/reports/latest.json
    python -m oficio.evals.report evals/reports/latest.json
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def render(results: dict) -> str:
    ext, sec = results.get("extraction"), results.get("security")
    rows: list[str] = ["| Metric | Result | Gate |", "|---|---|---|"]

    if ext:
        tp, fp, fn = ext["true_positives"], ext["false_positives"], ext["false_negatives"]
        precision = tp / (tp + fp) if (tp + fp) else 0.0
        recall = tp / (tp + fn) if (tp + fn) else 0.0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
        qty = ext["qty_exact"] / ext["qty_checked"] if ext["qty_checked"] else 0.0
        ask = (ext["needs_info_correct"] / ext["needs_info_expected"]
               if ext["needs_info_expected"] else 0.0)
        gate = "**PASS**" if ext["unevidenced_lines"] == 0 else "**FAIL**"
        rows += [
            f"| Item identification (F1) | {_pct(f1)} | ≥ 90% |",
            f"| Quantity exact match | {_pct(qty)} ({ext['qty_exact']}/{ext['qty_checked']}) | ≥ 90% |",
            f"| Asked instead of guessing | {_pct(ask)} ({ext['needs_info_correct']}/{ext['needs_info_expected']}) | ≥ 90% |",
            f"| **Invented values in output** | **{ext['unevidenced_lines']}** | **must be 0** — {gate} |",
            f"| Hallucination attempts blocked | {ext['blocked_hallucinations']} | — |",
            f"| Extraction errors | {ext['errors']} | 0 |",
            f"| Cost for {ext['cases']} cases | ${ext['cost_usd']:.4f} | — |",
        ]
    if sec:
        block = sec["blocked"] / sec["cases"] if sec["cases"] else 0.0
        gate = "**PASS**" if sec["leaked"] == 0 else "**FAIL**"
        rows += [
            f"| Attacks blocked | {sec['blocked']}/{sec['cases']} ({_pct(block)}) | 100% |",
            f"| **Attacks that reached the quote** | **{sec['leaked']}** | **must be 0** — {gate} |",
        ]
    if not ext and not sec:
        return "_No eval run recorded yet._"

    header = "<!-- generated by `python -m oficio.evals.report` — do not edit by hand -->"
    return header + "\n\n" + "\n".join(rows)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render an eval report")
    parser.add_argument("results", type=Path, nargs="?", default=Path("evals/reports/latest.json"))
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)

    if not args.results.exists():
        print("_No eval run recorded yet._")
        return 0
    text = render(json.loads(args.results.read_text()))
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text + "\n")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
